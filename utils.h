inline U64 get_bishop_attacks(int square, U64 occupancy) {
    occupancy &= BISHOP_ATTACK_MASK[square];
    U64 index = (occupancy * BISHOP_MAGIC_NUMS[square]) >> (64 - bishop_relevant_bits[square]);
    return BISHOP_ATTACK_PTRS[square][index];
}

inline U64 get_rook_attacks(int square, U64 occupancy) {
    occupancy &= ROOK_ATTACK_MASK[square];
    U64 index = (occupancy * ROOK_MAGIC_NUMS[square]) >> (64 - rook_relevant_bits[square]);
    return ROOK_ATTACK_PTRS[square][index];
}

inline U64 get_queen_attacks(int square, U64 occupancy) {
    return get_bishop_attacks(square, occupancy) | get_rook_attacks(square, occupancy);
}

