inline void set_bit(U64& bb, int square) {
    bb |= (1ULL << square);
}

inline void clear_bit(U64& bb, int square) {
    bb &= ~(1ULL << square);
}

inline bool get_bit(U64 bb, int square) {
    return (bb & (1ULL << square)) != 0;
}

inline void toggle_bit(U64& bb, int square) {
    bb ^= (1ULL << square);
}

inline Square getSquareFromNotation(std::string_view sq) {
    int index = ((sq[1] - '1') * 8) + static_cast<int>(sq[0] - 'a');
    return static_cast<Square>(index);
}

inline Color getOppositeColor(Color side) {
    return side == BLACK ? WHITE : BLACK;
}

inline std::string getStringFromSquare(auto sq) { // for debugging purposes
    int r = sq / 8; int f = sq % 8;
    return static_cast<char>('a'+f) + std::to_string(r+1);
}

inline Move makeMoveU16(auto from, auto to, MoveFlag flag) { // Can take Square or int
    // std::println("{} {}", getStringFromSquare(from), getStringFromSquare(to));
    // std::println("Move flag: {}", static_cast<int>(flag));
    // std::cout << std::bitset<4>(flag) << "\n";
    return (flag << 12) | (to << 6) | from;
}

inline std::string moveToString(Move move) {
    uint8_t to = (move >> 6) & 0x3F;
    uint8_t from = move & 0x3F;
    uint8_t flag = static_cast<MoveFlag>(move >> 12);
    std::string flagstr = "";
    if (flag >= 8) {
        if (((flag - 8) % 4) == 0) {
            flagstr = "k";
        } else if (((flag - 8) % 4) == 1) {
            flagstr = "b";
        } else if (((flag - 8) % 4) == 2) {
            flagstr = "r";
        } else if (((flag - 8) % 4) == 3) {
            flagstr = "q";
        }
    }
    return getStringFromSquare(from) + getStringFromSquare(to) + flagstr;
}

inline void printMove(Move move) {
    uint8_t flag = static_cast<MoveFlag>(move >> 12);
    std::println("Printing move: {}; Flag: {}", moveToString(move), flag);
}

inline void printMove(Move move, std::array<Piece, 64>& grid) {
    uint8_t flag = static_cast<MoveFlag>(move >> 12);
    Piece from = grid[move & 0x3F];
    Piece to = grid[(move >> 6) & 0x3F];
    std::println("Printing move: {}; From: {}; To: {}, Flag: {}", moveToString(move), static_cast<char>(from), static_cast<char>(to), flag);
}

